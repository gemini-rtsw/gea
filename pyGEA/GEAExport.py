def channelList(request):
    """Explicit channel names from CHANNELS (whitespace separated)."""
    return (request.get('CHANNELS', '') or '').split()


def patternList(request):
    """Regex pattern(s) from PATTERN. A pattern can match arbitrarily many PVs, so it
    is kept separate from explicit channels for both -match handling and sizing."""
    pattern = (request.get('PATTERN', '') or '').strip()
    return [pattern] if pattern else []


def epicsArchivers(request):
    """The EPICS (non-SQL) archivers named in the request. SQL archivers are not
    supported by this export path (same limitation as the plotter's spreadsheet)."""
    names = request.get('SYSTEMS', '').split() + request.get('SYSTEMS2', '').split()
    chanArchList, _sqlList = splitArchives(names)
    return chanArchList


def shouldRunInline(startTime, endTime, channels, patterns):
    """Decide whether to run in the web request (small) or hand off to the worker.

    A PATTERN can expand to an unknown (possibly huge) number of PVs, so anything with
    a pattern always goes async. For explicit channels the metric is
    (range seconds) * (#channels), capped by GEAVars.dataEx.exportInlineMaxChannelSeconds;
    we also cap the absolute range, since even a single high-rate channel over a long
    span can be enough to hang a CGI request."""
    if patterns:
        return False
    span = max(0, int(endTime.seconds) - int(startTime.seconds))
    if span > GEAVars.dataEx.exportInlineMaxChannelSeconds:
        return False
    return span * max(1, len(channels)) <= GEAVars.dataEx.exportInlineMaxChannelSeconds


